def replace_body(filepath, new_body):
    """查找 <h2 id="前言"> 到 </article> 之间的内容并替换"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Match from <h2 id="前言"> to </article> followed by article notice
    pattern = r'(<h2 id="前言">前言</h2>.*?</article>\s*\n\s*<!-- ===== 文章声明)'
    replacement = new_body + '\n\n<!-- ===== 文章声明'
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    
    if new_content == content:
        print(f"  WARNING: No match found in {filepath}")
        return False
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_content)
    return True

